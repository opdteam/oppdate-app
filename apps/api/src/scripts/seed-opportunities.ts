async function main() {
  const db = await initDb()

  // Use the first admin user as the creator, fall back to any user
  const [creator] = await db
    .select({ id: schema.users.id })
    .from(schema.users)
    .where(eq(schema.users.role, 'super_admin'))
    .limit(1)

  if (!creator) {
    console.error('No admin user found. Run yarn db:seed-admin first.')
    process.exit(1)
  }

  console.log(`Seeding ${opportunities.length} opportunities (created_by: ${creator.id})...`)

  for (const opp of opportunities) {
    const slug = opp.title
      .toLowerCase()
      .replace(/[^a-z0-9\s-]/g, '')
      .replace(/\s+/g, '-')
      .slice(0, 100)

    await db.insert(schema.opportunities).values({
      ...opp,
      slug,
      deadline: opp.deadline,
      applicationOpenDate: null,
      postSubmissionMessage: 'Your application has been received. The OppDate team will be in touch shortly.',
      oppDateApply: opp.oppdateServiceFeeUsd > 0,
      createdBy: creator.id,
    }).onConflictDoNothing()

    console.log(`  inserted: ${opp.title}`)
  }

  console.log('Done.')
  process.exit(0)
}

main().catch(err => {
  console.error(err)
  process.exit(1)
})
